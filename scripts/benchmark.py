"""Run the full benchmark: map all four sites, score them, write the results.

    python scripts/benchmark.py            regenerate examples/output/ and BENCHMARK.md
    python scripts/benchmark.py --check    regenerate into a temp dir and fail if the
                                           committed outputs are stale or any
                                           auto-accepted point is wrong (used by CI)
"""

from __future__ import annotations

import argparse
import filecmp
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from pointmap.evaluate import evaluate, per_site_markdown  # noqa: E402
from pointmap.export.brick import write_brick  # noqa: E402
from pointmap.export.haystack import write_haystack  # noqa: E402
from pointmap.export.report import write_report  # noqa: E402
from pointmap.export.tables import write_tables  # noqa: E402
from pointmap.pipeline import run  # noqa: E402
from pointmap.rules import load_rules  # noqa: E402

# file stem in data/raw and data/ground_truth -> site id
SITES = {
    "pine_paper_alc": "PINE-PAPER",
    "office_a_metasys": "OFFICE-A",
    "store_01_niagara": "STORE-01",
    "legacy_mix_chaos": "LEGACY-MIX",
}


def build(out_root: Path) -> tuple[str, int]:
    """Map every site into out_root and write BENCHMARK.md. Returns (markdown, silent errors)."""
    rules = load_rules()
    evaluations = []
    for stem, site in SITES.items():
        out = out_root / stem
        out.mkdir(parents=True, exist_ok=True)
        result = run(REPO / "data/raw" / f"{stem}.csv", site=site, rules=rules)
        write_tables(result.results, out)
        write_haystack(site, result.results, rules, out)
        write_brick(site, result.results, rules, out)
        write_report(result, out)
        evaluations.append(evaluate(out / "tagged_points.csv", REPO / "data/ground_truth" / f"{stem}.csv"))

    total = evaluations[0]
    for other in evaluations[1:]:
        total = total + other
    markdown = "\n".join([
        "# Benchmark results",
        "",
        "Generated by `python scripts/benchmark.py`. Do not edit by hand.",
        "",
        total.as_markdown(),
        "",
        "## By site",
        "",
        per_site_markdown(evaluations),
        "",
    ])
    (out_root / "BENCHMARK.md").write_text(markdown, encoding="utf-8")
    return markdown, len(total.silent_errors)


def _differences(expected: Path, actual: Path) -> list[str]:
    diffs = []
    for path in sorted(actual.rglob("*")):
        if path.is_file():
            rel = path.relative_to(actual)
            committed = expected / rel
            if not committed.exists() or not filecmp.cmp(committed, path, shallow=False):
                diffs.append(str(rel))
    return diffs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify committed outputs instead of rewriting them")
    args = parser.parse_args()
    committed = REPO / "examples/output"

    if not args.check:
        markdown, silent = build(committed)
        print(markdown)
        return 1 if silent else 0

    with tempfile.TemporaryDirectory() as tmp:
        markdown, silent = build(Path(tmp))
        stale = _differences(committed, Path(tmp))
    print(markdown)
    if stale:
        print("examples/output is stale; run `python scripts/benchmark.py` and commit:", file=sys.stderr)
        for rel in stale:
            print(f"  {rel}", file=sys.stderr)
    if silent:
        print(f"{silent} auto-accepted point(s) are wrong", file=sys.stderr)
    return 1 if (stale or silent) else 0


if __name__ == "__main__":
    raise SystemExit(main())
